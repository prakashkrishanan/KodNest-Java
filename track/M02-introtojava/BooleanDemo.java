public class BooleanDemo {
    public static void main(String[] args) {
        int solvedProblems = 24;
        int requiredProblems = 20;

        boolean targetReached = solvedProblems >= requiredProblems;

        System.out.println("Solved problems: " + solvedProblems);
        System.out.println("Required problems: " + requiredProblems);
        System.out.println("Target reached: " + targetReached);
    }
}
